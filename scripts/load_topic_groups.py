#!/usr/bin/env python3
"""
Load each paper's typical real-exam topic mix into exam_topic_groups (migration 038).

Source: wiki/reference/sopeec-exam-breakdown.csv, generated by
fsa-marketing/scripts/build_exam_breakdown_csv.py (that script owns the
topic -> chapter mapping; fix mapping problems there, then re-run this).
One CSV row = one topic group. Leveled practice exams draw each sitting's
questions per topic group; chapters are backend-only.

Usage (from the host):
  POSTGRES_PASSWORD=... python3 scripts/load_topic_groups.py --target scratch|test
  python3 scripts/load_topic_groups.py --sql-out /path/topic_groups.sql
Production never gets a direct connection from here: Russ runs
scripts/load_topic_groups_prod.sh, which applies the --sql-out file.
"""
import argparse
import csv
import json
import os
import re
import sys
from collections import Counter
from dataclasses import dataclass

DEFAULT_CSV = '/home/debian/wiki/reference/sopeec-exam-breakdown.csv'
# Keep in step with server/src/config/papersForClass.js.
ALL_PAPERS = ['2A1', '2A2', '2A3', '2B1', '2B2', '2B3',
              '3A1', '3A2', '3B1', '3B2', '4A', '4B']
TARGET_DBS = {'scratch': 'fsa_agent_scratch', 'test': 'fsa_agent_test'}


@dataclass
class TopicGroup:
    paper_code: str
    topic_key: str
    display_name: str
    exam_questions: int
    chapter_ids: list
    sort_order: int


def _slug(name: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', name.lower()).strip('-')


def parse_topic_groups(csv_path: str, papers: list) -> list:
    groups, order = [], Counter()
    with open(csv_path, newline='') as f:
        for row in csv.DictReader(f):
            paper = row['paper']
            if paper not in papers:
                continue
            chapters = [c.strip() for c in row['fsa_chapters'].split(';') if c.strip()]
            groups.append(TopicGroup(
                paper_code=paper,
                topic_key=_slug(row['topic_cluster']),
                display_name=row['topic_cluster'],
                exam_questions=int(row['typical_questions'] or 0),
                chapter_ids=[f'{paper}-{c}' for c in chapters],
                sort_order=order[paper],
            ))
            order[paper] += 1
    return groups


def validate(groups: list, chapter_ids_by_paper: dict) -> list:
    errors = []
    by_paper = {}
    for g in groups:
        by_paper.setdefault(g.paper_code, []).append(g)
    for paper, gs in by_paper.items():
        total = sum(g.exam_questions for g in gs)
        if total != 100:
            errors.append(f'{paper}: topic groups sum to {total}, not 100')
        seen = Counter(c for g in gs for c in g.chapter_ids)
        errors += [f'{paper}: chapter {c} is in {n} topic groups' for c, n in seen.items() if n > 1]
        keys = Counter(g.topic_key for g in gs)
        errors += [f'{paper}: topic_key {k} repeats' for k, n in keys.items() if n > 1]
        for c in sorted(chapter_ids_by_paper.get(paper, set()) - set(seen)):
            errors.append(f'{paper}: chapter {c} has exam questions but no topic group')
    return errors


def _sql_literal(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def build_sql(groups: list) -> str:
    papers = sorted({g.paper_code for g in groups})
    lines = ['BEGIN;']
    for g in groups:
        arr = 'ARRAY[' + ','.join(_sql_literal(c) for c in g.chapter_ids) + ']::text[]'
        lines.append(
            'INSERT INTO exam_topic_groups (paper_code, topic_key, display_name, exam_questions, chapter_ids, sort_order) '
            f'VALUES ({_sql_literal(g.paper_code)}, {_sql_literal(g.topic_key)}, {_sql_literal(g.display_name)}, '
            f'{g.exam_questions}, {arr}, {g.sort_order}) '
            'ON CONFLICT (paper_code, topic_key) DO UPDATE SET display_name = EXCLUDED.display_name, '
            'exam_questions = EXCLUDED.exam_questions, chapter_ids = EXCLUDED.chapter_ids, sort_order = EXCLUDED.sort_order;'
        )
    for p in papers:
        keys = ','.join(_sql_literal(g.topic_key) for g in groups if g.paper_code == p)
        lines.append(f'DELETE FROM exam_topic_groups WHERE paper_code = {_sql_literal(p)} AND topic_key NOT IN ({keys});')
    lines.append('COMMIT;')
    return '\n'.join(lines) + '\n'


def load(conn, groups: list) -> int:
    with conn.cursor() as cur:
        cur.execute(build_sql(groups))
    return len(groups)


def _connect(dbname: str):
    import psycopg2
    return psycopg2.connect(
        host=os.environ.get('POSTGRES_HOST', 'localhost'),
        port=int(os.environ.get('POSTGRES_PORT', '5434')),
        dbname=dbname,
        user=os.environ.get('POSTGRES_USER', 'postgres'),
        password=os.environ['POSTGRES_PASSWORD'],
    )


def _db_chapters(conn, papers: list) -> dict:
    with conn.cursor() as cur:
        cur.execute(
            """SELECT DISTINCT course_id, chapter_id FROM questions
               WHERE course_id = ANY(%s) AND chapter_id IS NOT NULL AND standalone
                 AND options IS NOT NULL AND jsonb_array_length(options) > 0""",
            (papers,))
        out = {}
        for course, chapter in cur.fetchall():
            out.setdefault(course, set()).add(chapter)
        return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--csv', default=DEFAULT_CSV)
    ap.add_argument('--papers', default=','.join(ALL_PAPERS))
    dest = ap.add_mutually_exclusive_group(required=True)
    dest.add_argument('--target', choices=sorted(TARGET_DBS))
    dest.add_argument('--sql-out')
    args = ap.parse_args()

    papers = args.papers.split(',')
    groups = parse_topic_groups(args.csv, papers)

    if args.sql_out:
        errors = validate(groups, {})
        if errors:
            print('\n'.join(errors)); return 1
        with open(args.sql_out, 'w') as f:
            f.write(build_sql(groups))
        print(f'wrote {len(groups)} topic groups for {len(papers)} papers to {args.sql_out}')
        return 0

    conn = _connect(TARGET_DBS[args.target])
    errors = validate(groups, _db_chapters(conn, papers))
    if errors:
        print('\n'.join(errors)); return 1
    n = load(conn, groups)
    conn.commit()
    print(f'{args.target}: {n} topic groups loaded for {len(papers)} papers, 0 validation errors')
    print(json.dumps({p: sum(1 for g in groups if g.paper_code == p) for p in papers}))
    return 0


if __name__ == '__main__':
    sys.exit(main())
